const sizes: Record<ButtonSize, string> = {
  sm: "h-8 gap-1.5 rounded-lg px-3",
  lg: "h-10 rounded-lg px-6",
};

export function buttonVariants({
  variant,
  size,
  className,
}: {
  variant: ButtonVariant;
  size: ButtonSize;
  className?: string;
}) {
  return cn(baseButton, variants[variant], sizes[size], className);
}
